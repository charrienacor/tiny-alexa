"""Train the two-head TCN (intent head + slot head).

Run from the repo root:   python src/train.py
Loss = CrossEntropy(intent) + CrossEntropy(slot), with label smoothing. The
logged "acc" is the end-to-end command accuracy: both heads decoded jointly
over the 31 valid (intent, slot) combinations.

The best checkpoint is chosen by group-balanced validation accuracy (mean of
foreign and Filipino-English speaker accuracy), so the 16 Filipino-English
speakers are not drowned out by the 84 others.
Saves the best model to models/TCN.pt and the training log to
results/history.csv. All plots are generated by evaluate.py.
"""

import time
import argparse
import csv
import json
import math
import platform
import random
import socket
import subprocess
from datetime import datetime
from pathlib import Path

import numpy as np
import torch
from torch.utils.data import DataLoader, WeightedRandomSampler

from dataset import GROUPS, VCMDataset, load_labels
from features import load_intents_slots
from model import TCN

ROOT = Path(__file__).resolve().parents[1]


def gpu_info(device):
    """Machine snapshot for results/train_config.json (host + GPU details)."""
    info = {"hostname": socket.gethostname(),
            "platform": platform.platform(),
            "python": platform.python_version()}
    if device == "cuda":
        props = torch.cuda.get_device_properties(0)
        info.update({
            "gpu": torch.cuda.get_device_name(0),
            "gpu_count": torch.cuda.device_count(),
            "gpu_memory_gib": round(props.total_memory / 2**30, 1),
            "cuda": torch.version.cuda,
            "driver": _nvidia_driver(),
        })
    return info


def _nvidia_driver():
    """Driver version from nvidia-smi (None when unavailable)."""
    try:
        out = subprocess.check_output(
            ["nvidia-smi", "--query-gpu=driver_version", "--format=csv,noheader"],
            text=True, timeout=5).strip().splitlines()
        return out[0] if out else None
    except (OSError, subprocess.SubprocessError):
        return None


def run_epoch(model, loader, loss_fn, optimizer, device, combo, scheduler=None):
    """One pass over the data. optimizer=None means validation.

    combo is a (31, 2) tensor mapping each label to its
    (intent index, slot index) — used to decode the two heads jointly.
    scheduler (optional) is stepped once per training batch.
    Returns (loss, command_acc, intent_acc, slot_acc, per-item correct).
    """
    model.train(optimizer is not None)
    total_loss, correct_i, correct_s, n = 0.0, 0, 0, 0
    hits = []
    with torch.set_grad_enabled(optimizer is not None):
        for mel, intent, slot, label in loader:
            mel = mel.to(device)
            intent, slot, label = (intent.to(device), slot.to(device),
                                   label.to(device))
            intent_logits, slot_logits = model(mel)
            loss = loss_fn(intent_logits, intent) + loss_fn(slot_logits, slot)
            if optimizer is not None:
                optimizer.zero_grad()
                loss.backward()
                # gradient clipping: keeps training stable across the cosine LR sweep
                torch.nn.utils.clip_grad_norm_(model.parameters(), 5.0)
                optimizer.step()
                if scheduler is not None:
                    scheduler.step()
            total_loss += loss.item() * mel.size(0)
            with torch.no_grad():
                # joint decode: best valid (intent, slot) combination
                log_pi = torch.log_softmax(intent_logits, dim=1)
                log_ps = torch.log_softmax(slot_logits, dim=1)
                scores = log_pi[:, combo[:, 0]] + log_ps[:, combo[:, 1]]  # (B, 31)
                hits.append((scores.argmax(1) == label).cpu())
                correct_i += (intent_logits.argmax(1) == intent).sum().item()
                correct_s += (slot_logits.argmax(1) == slot).sum().item()
            n += mel.size(0)
    hits = torch.cat(hits).numpy()
    return total_loss / n, hits.mean(), correct_i / n, correct_s / n, hits

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--data", default=ROOT / "data", help="dataset folder")
    parser.add_argument("--epochs", type=int, default=40)
    parser.add_argument("--batch-size", type=int, default=64)
    parser.add_argument("--lr", type=float, default=1e-3)
    parser.add_argument("--workers", type=int, default=4)
    parser.add_argument("--warmup", type=int, default=2,
                        help="epochs of linear LR warmup before the cosine decay")
    parser.add_argument("--weight-decay", type=float, default=1e-2)
    parser.add_argument("--label-smoothing", type=float, default=0.1)
    parser.add_argument("--filipino-weight", type=float, default=2.0,
                        help="sampling weight of Filipino-English training "
                             "utterances relative to the others")
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--patience", type=int, default=10,
                        help="stop when val acc hasn't improved for this many epochs (0 = off)")
    args = parser.parse_args()

    torch.manual_seed(args.seed)
    np.random.seed(args.seed)
    random.seed(args.seed)
    if torch.cuda.is_available():
        device = "cuda"          # NVIDIA GPU
    elif torch.backends.mps.is_available():
        device = "mps"           # Apple Silicon
    else:
        device = "cpu"
    print(f"device: {device}")

    labels, label_to_idx = load_labels(args.data)
    intents, slots, label_map = load_intents_slots(args.data)
    intent_to_idx = {name: i for i, name in enumerate(intents)}
    slot_to_idx = {name: i for i, name in enumerate(slots)}
    # label -> (intent index, slot index); used to decode the two heads
    combo = torch.tensor([[intent_to_idx[label_map[l][0]],
                           slot_to_idx[label_map[l][1]]] for l in labels],
                         dtype=torch.long, device=device)

    train_ds = VCMDataset(args.data, "train", label_to_idx, augment=True)
    valid_ds = VCMDataset(args.data, "valid", label_to_idx)
    print(f"train: {len(train_ds)} utterances, valid: {len(valid_ds)}, "
          f"intents: {len(intents)}, slots: {len(slots)}")

    # oversample the Filipino-English speakers (13 of 80 training speakers)
    weights = [args.filipino_weight if g == "filipino" else 1.0
               for g in train_ds.groups]
    sampler = WeightedRandomSampler(weights, num_samples=len(train_ds),
                                    replacement=True)
    # persistent workers: macOS spawns them, which is slow to redo per epoch
    loader_kw = dict(batch_size=args.batch_size, num_workers=args.workers,
                     pin_memory=device == "cuda",
                     persistent_workers=args.workers > 0)
    train_dl = DataLoader(train_ds, sampler=sampler, **loader_kw)
    valid_dl = DataLoader(valid_ds, **loader_kw)
    valid_groups = np.array(valid_ds.groups)

    model = TCN(n_intents=len(intents), n_slots=len(slots)).to(device)
    n_params = sum(p.numel() for p in model.parameters())
    print(f"model: {n_params:,} parameters ({n_params * 4 / 1e6:.1f} MB fp32)")

    loss_fn = torch.nn.CrossEntropyLoss(label_smoothing=args.label_smoothing)
    optimizer = torch.optim.AdamW(model.parameters(), lr=args.lr,
                                  weight_decay=args.weight_decay)
    # per-step schedule: linear warmup, then cosine decay to 1e-5 by the
    # last planned epoch
    steps_per_epoch = len(train_dl)
    warmup_steps = args.warmup * steps_per_epoch
    total_steps = args.epochs * steps_per_epoch
    min_ratio = 1e-5 / args.lr

    def lr_lambda(step):
        if step < warmup_steps:
            return (step + 1) / warmup_steps
        t = (step - warmup_steps) / max(1, total_steps - warmup_steps)
        return min_ratio + (1 - min_ratio) * 0.5 * (1 + math.cos(math.pi * t))

    scheduler = torch.optim.lr_scheduler.LambdaLR(optimizer, lr_lambda)

    (ROOT / "models").mkdir(exist_ok=True)
    results = ROOT / "results"
    results.mkdir(exist_ok=True)

    # machine + recipe snapshot: bench_gpu.py folds this into the dashboard
    # report, so the A100 run is self-documenting
    config = {
        "timestamp": datetime.now().astimezone().isoformat(timespec="seconds"),
        "objective": (f"cross-entropy (intent head) + cross-entropy (slot head), "
                      f"label smoothing {args.label_smoothing:g}; "
                      "joint decode over the 31 valid (intent, slot) combinations"),
        "optimizer": (f"AdamW (lr={args.lr:g}, weight_decay={args.weight_decay:g}) + "
                      f"{args.warmup}-epoch linear warmup + per-step cosine "
                      f"decay to 1e-5 over {args.epochs} epochs"),
        "augmentation": ("speed 0.9-1.1, time shift <=0.25 s, white/pink noise "
                         "5-30 dB SNR (p=0.5), SpecAugment 2x8 bands + 2x20 frames"),
        "filipino_weight": args.filipino_weight,
        "selection": "mean of foreign and Filipino-English val accuracy",
        "seed": args.seed,
        "epochs_planned": args.epochs,
        "batch_size": args.batch_size,
        "patience": args.patience,
        "train_utts": len(train_ds),
        "valid_utts": len(valid_ds),
        "steps_per_epoch": math.ceil(len(train_ds) / args.batch_size),
        "model_params": n_params,
        "torch": torch.__version__,
        **gpu_info(device),
    }
    (results / "train_config.json").write_text(
        json.dumps(config, indent=2) + "\n", encoding="utf-8")

    # training log: accuracies in percent; "acc" = joint command accuracy
    # (intent + slot both correct) — the same numbers as the epoch printout.
    # val_select = mean of the per-group accuracies (checkpoint selection).
    # Rewritten after every epoch, so an interrupted run keeps its log.
    def save_history():
        with open(results / "history.csv", "w", newline="") as f:
            writer = csv.writer(f)
            writer.writerow(["epoch", "train_acc", "val_acc",
                             "val_intent_acc", "val_slot_acc",
                             *(f"val_acc_{g}" for g in GROUPS), "val_select",
                             "val_loss", "lr", "elapsed_s"])
            writer.writerows(history)

    history = []
    best_acc = -1.0
    epochs_since_best = 0
    for epoch in range(1, args.epochs + 1):
        t0 = time.perf_counter()
        lr_used = optimizer.param_groups[0]["lr"]   # lr at the start of this epoch
        tr_loss, tr_acc, tr_ia, tr_sa, _ = run_epoch(
            model, train_dl, loss_fn, optimizer, device, combo, scheduler)
        va_loss, va_acc, va_ia, va_sa, va_hits = run_epoch(
            model, valid_dl, loss_fn, None, device, combo)
        elapsed = time.perf_counter() - t0
        group_acc = [va_hits[valid_groups == g].mean() for g in GROUPS]
        va_sel = float(np.mean(group_acc))          # checkpoint selection metric
        history.append([epoch, tr_acc * 100, va_acc * 100,
                        va_ia * 100, va_sa * 100,
                        *(a * 100 for a in group_acc), va_sel * 100,
                        va_loss, lr_used, elapsed])
        save_history()
        star = "*" if va_sel > best_acc else " "    # * = new best model saved
        print(f"epoch {epoch}/{args.epochs}  train {tr_acc:.3f}  val {va_acc:.3f}  "
              f"(foreign {group_acc[0]:.3f} filipino {group_acc[1]:.3f})  "
              f"intent {va_ia:.3f}  slot {va_sa:.3f}  loss {va_loss:.3f}  "
              f"lr {lr_used:.2e} ({elapsed:5.1f}s) {star}")
        if va_sel > best_acc:                       # keep the best model
            best_acc = va_sel
            epochs_since_best = 0
            torch.save(model.state_dict(), ROOT / "models" / "TCN.pt")
        else:
            epochs_since_best += 1
            if args.patience and epochs_since_best >= args.patience:
                print(f"early stop: no improvement in {args.patience} epochs")
                break

    print(f"done. best group-balanced validation accuracy: {best_acc:.3f}")


if __name__ == "__main__":
    main()